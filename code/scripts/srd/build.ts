// Builds code/src/data/srd/*.json from the extracted SRD text (see README.md). Run from code/: npm run srd.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { catalogId, type Entry, type ItemEntry, type ProfEntry } from '../../src/catalog/schema.ts';
import { applyOverlay, type Overlay } from '../lib/overlay.ts';
import { writeEntries } from '../lib/write.ts';
import { copyBase, parseArmor, parseGear, parseMagicItems, parseMounts, parseTools, parseWeapons } from './items.ts';
import { parseClass } from './classes.ts';
import { parseBackgrounds, parseFeats, parseSpecies } from './origins.ts';
import { parseLanguages, parseRules } from './rules.ts';
import { parseSpells } from './spells.ts';
import { layoutBetween, section } from './text.ts';

const root = new URL('../../../', import.meta.url);
const srdText = readFileSync(new URL('resources/srd/srd.txt', root), 'utf8');
const layout = readFileSync(new URL('resources/srd/srd-layout.txt', root), 'utf8');
const overlay = (name: string): Overlay => {
  const p = new URL(`code/scripts/srd/overlay/${name}.json`, root);
  return existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : {};
};
// post: a step after the overlay (items copy their base item's fields, which the overlay names).
const out = (name: string, entries: Entry[], post = (es: Entry[]) => es) => {
  writeEntries(new URL(`code/src/data/srd/${name}.json`, root).pathname, post(applyOverlay(entries, overlay(name))));
  console.log(`${name}: ${entries.length} entries`);
};

out('spells', parseSpells(section(srdText, 'Acid Arrow', 'Rules Glossary', 'Spell Descriptions')));
const items: ItemEntry[] = [
  ...parseWeapons(layoutBetween(layout, /^\s+Name\s+Damage\s+Properties/, /^\s+Pistol\s/)),
  ...parseArmor(layoutBetween(layout, /^\s+Armor\s+Armor Class \(AC\)/, /^\s+Shield\s+\+2/)),
  ...parseGear(section(srdText, 'Acid (25 GP)', 'Mounts and Vehicles'),
    layoutBetween(layout, /^\s+Adventuring Gear\s+Item\s+Weight/, /^\s+Ink\s+—/) + '\n' + layoutBetween(layout, /^\s+Type\s+Amount Storage/, /^\s+Needles\s/)),
  ...parseMounts(layout),
  ...parseTools(section(srdText, 'Alchemist’s Supplies (50 GP)', 'Adventuring Gear')),
  ...parseMagicItems(section(srdText, 'Adamantine Armor', 'Monsters', 'Magic Items A–Z'))
];
out('items', items, (es) => copyBase(es as ItemEntry[]));
const [species, traits] = parseSpecies(section(srdText, 'Dragonborn', 'Feats', 'Species Descriptions'), layout);
out('origins', [
  ...parseFeats(section(srdText, 'Origin Feats', 'Equipment', 'Feat Descriptions')),
  ...parseBackgrounds(section(srdText, 'Acolyte', 'Character Species', 'Background Descriptions')),
  ...species, ...traits
]);
const CLASSES = ['Barbarian', 'Bard', 'Cleric', 'Druid', 'Fighter', 'Monk', 'Paladin', 'Ranger', 'Rogue', 'Sorcerer', 'Warlock', 'Wizard'];
out('classes', CLASSES.flatMap((c, i) => {
  const [cls, subs, feats] = parseClass(section(srdText, `Core ${c} Traits`, CLASSES[i + 1] ? `Core ${CLASSES[i + 1]} Traits` : 'Character Origins'), layout);
  return [cls, ...subs, ...feats];
}));
out('rules', parseRules(section(srdText, 'Rules Glossary', 'Gameplay Toolbox')));

// Proficiency names: armor training, weapons, tools (with their variants) and languages. They go into the catalog and,
// as plain names, into src/catalog/names.ts, which the main bundle imports for migrate()'s Training match.
const title = (s: string) => s.replace(/(^|[\s-])([a-z])/g, (_, a: string, b: string) => a + b.toUpperCase());
const prof = (name: string, cat: ProfEntry['cat'], short?: string): ProfEntry =>
  ({ id: catalogId('prof', name), kind: 'prof', name, src: 'srd', desc: '', cat, ...(short ? { short } : {}) });
const tools = items.filter((e) => e.cat === 'tool');
const profs: ProfEntry[] = [
  prof('Light armor', 'armor', 'Light'), prof('Medium armor', 'armor', 'Medium'), prof('Heavy armor', 'armor', 'Heavy'), prof('Shields', 'armor', 'Shield'),
  prof('Simple weapons', 'weapon', 'Simple'), prof('Martial weapons', 'weapon', 'Martial'),
  ...items.filter((e) => e.cat === 'weapon').map((e) => prof(e.name, 'weapon')),
  ...tools.map((e) => prof(e.name, 'tool')),
  ...tools.flatMap((e) => (/^Variants: (.*)$/m.exec(e.desc)?.[1].split(/,(?![^(]*\))\s*/) ?? []).map((v) => prof(title(v.replace(/\s*\(.*$/, '')), 'tool'))),
  ...parseLanguages(section(srdText, 'Standard Languages', 'Step 3: Ability Scores')).map((l) => prof(l, 'language'))
];
out('profs', profs);
writeFileSync(new URL('code/src/catalog/names.ts', root), `// Generated by \`npm run srd\` (scripts/srd/build.ts) from SRD 5.2.1: proficiency names for matching Training text.
// Part of the main bundle and import-free, so migrate() can use it synchronously; never add pack names here.
export type ProfCat = 'armor' | 'weapon' | 'tool' | 'language';
export const PROF_NAMES: { id: string; name: string; cat: ProfCat; short?: string }[] = [
${profs.map((p) => `  { ${Object.entries({ id: p.id, name: p.name, cat: p.cat, short: p.short }).filter(([, v]) => v).map(([k, v]) => `${k}: '${v!.replace(/'/g, "\\'")}'`).join(', ')} }`).join(',\n')}
];
`);
